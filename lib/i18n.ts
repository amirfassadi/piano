export type CopyKey = keyof typeof dictionaries.en;

export function t(locale: Locale, key: CopyKey): string {
  return dictionaries[locale][key];
}

const categoryLabels: Record<string, Record<Locale, string>> = {
  "همه": { en: "All", fa: "همه" },
  "ترانه‌های ایرانی": { en: "Iranian songs", fa: "ترانه‌های ایرانی" },
  "کلاسیک": { en: "Classical", fa: "کلاسیک" },
  "موسیقی فیلم": { en: "Film scores", fa: "موسیقی فیلم" },
  "بی‌کلام": { en: "Instrumental", fa: "بی‌کلام" },
  "محلی": { en: "Folk", fa: "محلی" },
  "ترانه‌های جهان": { en: "World songs", fa: "ترانه‌های جهان" },
};

export function categoryLabel(category: string, locale: Locale): string {
  return categoryLabels[category]?.[locale] ?? category;
}

export function levelLabel(level: string, locale: Locale): string {
  const key: CopyKey = level.includes("آسان") && level.includes("سخت")
    ? "levelEasyAdvanced"
    : level.includes("آسان") && level.includes("متوسط")
      ? "levelEasyIntermediate"
      : level.includes("متوسط") && level.includes("سخت")
        ? "levelIntermediateAdvanced"
        : level.includes("آسان")
          ? "levelEasy"
          : level.includes("متوسط")
            ? "levelIntermediate"
            : level.includes("سخت")
              ? "levelAdvanced"
              : "levelSelect";
  return t(locale, key);
}

export function roleLabel(role: string, locale: Locale): string {
  if (role === "آهنگساز") return t(locale, "roleComposer");
  if (role === "خواننده") return t(locale, "roleSinger");
  return role;
}

export function accessLabel(price: string, isFree: boolean | undefined, locale: Locale): string {
  if (isFree || price === "رایگان") return t(locale, "labelFree");
  if (price.startsWith("تکی")) {
    if (locale === "fa") return price;
    const raw = price.match(/[۰-۹0-9٬,]+/)?.[0];
    if (!raw) return t(locale, "labelSingle");
    const western = raw.replace(/[۰-۹]/g, (digit) => String("۰۱۲۳۴۵۶۷۸۹".indexOf(digit))).replace(/[٬,]/g, "");
    const amount = Number(western);
    return Number.isFinite(amount) ? `${t(locale, "labelSingle")} · ${new Intl.NumberFormat("en-US").format(amount)} toman` : t(locale, "labelSingle");
  }
  return t(locale, "labelVaries");
}
